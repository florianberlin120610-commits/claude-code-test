async function main() {
  await prisma.post.deleteMany();

  const avgViews = Math.round(
    POSTS.filter((p) => p.status === "published").reduce((s, p) => s + p.views, 0) /
      POSTS.filter((p) => p.status === "published").length
  );

  for (const raw of POSTS) {
    const weekday = getWeekday(raw.publishedAt);
    const engagementRate = calcEngagementRate(raw);
    const hookScore = raw.status === "draft" ? 0 : calcHookScore({ ...raw, purchases: raw.purchases ?? null }, avgViews);

    await prisma.post.create({
      data: {
        ...raw,
        weekday,
        engagementRate,
        hookScore,
        seriesName: raw.seriesName ?? null,
        linkClicks: null,
        purchases: raw.purchases ?? null,
      },
    });
  }

  console.log(`Seeded ${POSTS.length} posts.`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
